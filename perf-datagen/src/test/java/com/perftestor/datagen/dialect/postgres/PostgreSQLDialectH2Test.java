package com.perftestor.datagen.dialect.postgres;

import com.perftestor.datagen.DefaultDataGenEngine;
import com.perftestor.datagen.executor.JdbcBatchExecutor;
import com.perftestor.datagen.model.DataGenSpec;
import com.perftestor.datagen.model.EngineListener;
import com.perftestor.datagen.model.EngineResult;
import com.perftestor.datagen.model.FieldRule;
import com.perftestor.datagen.model.SchemaMetadata;
import com.perftestor.datagen.model.TableSpec;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.Statement;
import java.util.List;
import java.util.concurrent.atomic.AtomicInteger;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * PostgreSQL 方言单测：H2 {@code MODE=PostgreSQL} 复用现有 SPI 测试模式（与 MySQLDialectH2Test 对齐），
 * 覆盖 URL 路由/标识符引用/SQL 构建/元数据（主键+外键）/行数，以及引擎全链路（Dry-Run + 正式写入）。
 */
class PostgreSQLDialectH2Test {

    /** 测试方言：复用 PostgreSQLDialect 全部实现，仅放开 URL 前缀（H2 PG 兼容模式无 pg_catalog/pg_enum） */
    static class H2PgDialect extends PostgreSQLDialect {
        @Override
        public boolean supports(String jdbcUrl) {
            return jdbcUrl != null && jdbcUrl.startsWith("jdbc:h2:");
        }

        @Override
        public String enrichJdbcUrl(String jdbcUrl) {
            return jdbcUrl;
        }
    }

    private static final PostgreSQLDialect DIALECT = new PostgreSQLDialect();
    private static final String URL = "jdbc:h2:mem:pg" + System.nanoTime()
            + ";MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE;DB_CLOSE_DELAY=-1";

    private static final DefaultDataGenEngine ENGINE = new DefaultDataGenEngine(
            List.of(new H2PgDialect()), new JdbcBatchExecutor(), List.of());

    @BeforeAll
    static void initDb() throws Exception {
        try (Connection c = DriverManager.getConnection(URL, "sa", ""); Statement st = c.createStatement()) {
            // PG 风格自增：GENERATED BY DEFAULT AS IDENTITY（H2 PG 模式与 PG 10+ 通用）
            st.execute("CREATE TABLE perf_user (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "name VARCHAR(64), age INT, status VARCHAR(16))");
            st.execute("CREATE TABLE perf_order (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "user_id BIGINT NOT NULL, amount DECIMAL(12,2), status VARCHAR(16), "
                    + "CONSTRAINT fk_o_u FOREIGN KEY (user_id) REFERENCES perf_user(id))");
        }
    }

    // ---------------- URL 路由与 SQL 构建 ----------------

    @Test
    void supportsPostgresUrlOnly() {
        assertTrue(DIALECT.supports("jdbc:postgresql://localhost:5432/demo"));
        assertFalse(DIALECT.supports("jdbc:mysql://localhost:3306/demo"));
        assertFalse(DIALECT.supports(null));
    }

    @Test
    void enrichJdbcUrlAppendsBatchedInsertsAndStringType() {
        assertEquals("jdbc:postgresql://h/d?reWriteBatchedInserts=true&stringtype=unspecified",
                DIALECT.enrichJdbcUrl("jdbc:postgresql://h/d"));
        assertEquals("jdbc:postgresql://h/d?sslmode=disable&reWriteBatchedInserts=true&stringtype=unspecified",
                DIALECT.enrichJdbcUrl("jdbc:postgresql://h/d?sslmode=disable"));
        String enriched = "jdbc:postgresql://h/d?reWriteBatchedInserts=true&stringtype=unspecified";
        assertEquals(enriched, DIALECT.enrichJdbcUrl(enriched), "两个参数均存在时原样返回，不重复追加");
    }

    @Test
    void enrichJdbcUrlKeepsCustomStringType() {
        String url = "jdbc:postgresql://h/d?stringtype=varchar";
        assertEquals("jdbc:postgresql://h/d?stringtype=varchar&reWriteBatchedInserts=true",
                DIALECT.enrichJdbcUrl(url), "用户显式指定 stringtype 时不覆盖");
    }

    @Test
    void quoteIdentifierUsesDoubleQuotes() {
        assertEquals("\"perf_order\"", DIALECT.quoteIdentifier("perf_order"));
        assertEquals("\"we\"\"ird\"", DIALECT.quoteIdentifier("we\"ird"), "内嵌双引号转义");
        assertEquals("\"\"", DIALECT.quoteIdentifier(null));
    }

    @Test
    void buildInsertSqlQuotedAndPlaceholder() {
        assertEquals("INSERT INTO \"perf_order\" (\"user_id\", \"amount\") VALUES (?, ?)",
                DIALECT.buildInsertSql("perf_order", List.of("user_id", "amount")));
    }

    // ---------------- 枚举发现（PG 特有） ----------------

    @Test
    void parseCheckDefinitionArrayAndInList() {
        assertEquals(List.of("PENDING", "PAID", "SHIPPED"), PostgreSQLDialect.parseCheckDefinition(
                "CHECK ((status = ANY (ARRAY['PENDING'::character varying, "
                        + "'PAID'::character varying, 'SHIPPED'::character varying])))"));
        assertEquals(List.of("A", "B"), PostgreSQLDialect.parseCheckDefinition("CHECK ((code IN ('A', 'B')))"));
        assertEquals(List.of("1", "2", "3"), PostgreSQLDialect.parseCheckDefinition("CHECK ((level IN (1, 2, 3)))"));
        assertTrue(PostgreSQLDialect.parseCheckDefinition(null).isEmpty());
        assertTrue(PostgreSQLDialect.parseCheckDefinition("CHECK ((age > 0))").isEmpty(), "非枚举约束不误报");
    }

    @Test
    void serialDefaultDetected() {
        assertTrue(PostgreSQLDialect.isSerialDefault("nextval('perf_user_id_seq'::regclass)"));
        assertTrue(PostgreSQLDialect.isSerialDefault("NEXTVAL('s'::regclass)"));
        assertFalse(PostgreSQLDialect.isSerialDefault("0"));
        assertFalse(PostgreSQLDialect.isSerialDefault(null));
    }

    // ---------------- 元数据读取 ----------------

    @Test
    void fetchMetadataColumnsPkAndFk() throws Exception {
        try (Connection c = DriverManager.getConnection(URL, "sa", "")) {
            SchemaMetadata user = DIALECT.fetchMetadata(c, "perf_user");
            assertEquals("perf_user", user.getTableName());
            assertNotNull(user.findColumn("name"));
            assertTrue(user.getPrimaryKeys().contains("id"));
            assertTrue(user.findColumn("id").isPrimaryKey(), "主键列应标记 primaryKey");
            assertTrue(user.getRowCount() >= 0);

            SchemaMetadata order = DIALECT.fetchMetadata(c, "perf_order");
            assertFalse(order.getForeignKeys().isEmpty(), "应读出声明外键");
            assertEquals("user_id", order.getForeignKeys().get(0).getFkColumn());
            assertEquals("perf_user", order.getForeignKeys().get(0).getPkTable());
        }
    }

    @Test
    void tableRowCountMatches() throws Exception {
        try (Connection c = DriverManager.getConnection(URL, "sa", "");
             Statement st = c.createStatement()) {
            st.execute("DELETE FROM perf_order");
            st.execute("DELETE FROM perf_user");
            assertEquals(0, DIALECT.tableRowCount(c, "perf_user"));
            st.execute("INSERT INTO perf_user (name, age, status) VALUES ('a', 1, 'NEW')");
            assertEquals(1, DIALECT.tableRowCount(c, "perf_user"));
            assertEquals(-1, DIALECT.tableRowCount(c, "no_such_table"), "表不存在返回 -1 不抛异常");
        }
    }

    // ---------------- 引擎全链路（H2 PG 模式） ----------------

    private static DataGenSpec spec(boolean dryRun) {
        DataGenSpec spec = new DataGenSpec();
        spec.setJdbcUrl(URL);
        spec.setDbUser("sa");
        spec.setDbPassword("");
        spec.setDryRun(dryRun);
        return spec;
    }

    private static FieldRule ref(String table, String column) {
        FieldRule r = new FieldRule();
        r.setType(FieldRule.TYPE_REF);
        r.setTable(table);
        r.setColumn(column);
        return r;
    }

    private static int count(String sql) throws Exception {
        try (Connection c = DriverManager.getConnection(URL, "sa", "");
             var rs = c.createStatement().executeQuery(sql)) {
            rs.next();
            return rs.getInt(1);
        }
    }

    @Test
    void engineDryRunUnderPostgresDialect() throws Exception {
        DataGenSpec spec = spec(true);
        TableSpec u = new TableSpec("perf_user", 20);
        TableSpec o = new TableSpec("perf_order", 50);
        o.getFields().put("user_id", ref("perf_user", "id"));
        spec.getTables().add(u);
        spec.getTables().add(o);

        EngineResult r = ENGINE.execute(spec, noopListener());
        assertTrue(r.isSuccess(), r.getErrorMsg());
        assertEquals(70, r.getTotalRows());
        assertEquals(2, r.getTableStats().size());
        assertEquals(0, count("SELECT COUNT(*) FROM perf_user"), "Dry-Run 不得写入");
    }

    @Test
    void engineRealInsertUnderPostgresDialect() throws Exception {
        try (Connection c = DriverManager.getConnection(URL, "sa", ""); Statement st = c.createStatement()) {
            st.execute("DELETE FROM perf_order");
            st.execute("DELETE FROM perf_user");
        }
        DataGenSpec spec = spec(false);
        TableSpec u = new TableSpec("perf_user", 30);
        TableSpec o = new TableSpec("perf_order", 60);
        o.getFields().put("user_id", ref("perf_user", "id"));
        spec.getTables().add(u);
        spec.getTables().add(o);

        AtomicInteger progress = new AtomicInteger();
        EngineResult r = ENGINE.execute(spec, new EngineListener() {
            @Override
            public void onProgress(long total, long done, String table) {
                progress.incrementAndGet();
            }

            @Override
            public void onHints(List<com.perftestor.datagen.model.MagicHint> m,
                                List<com.perftestor.datagen.model.RelationHint> rel) {
            }
        });
        assertTrue(r.isSuccess(), r.getErrorMsg());
        assertEquals(90, r.getInsertedRows());
        assertEquals(30, count("SELECT COUNT(*) FROM perf_user"));
        assertEquals(60, count("SELECT COUNT(*) FROM perf_order"));
        assertEquals(0, count("SELECT COUNT(*) FROM perf_order o WHERE o.user_id NOT IN "
                + "(SELECT id FROM perf_user)"), "外键引用必须全部落在父表 ID 池内");
        assertTrue(progress.get() > 0, "应回调进度");
    }

    @Test
    void engineRejectsUnregisteredUrl() {
        DataGenSpec spec = new DataGenSpec();
        spec.setJdbcUrl("jdbc:oracle:thin:@h:1521/x");
        spec.setDbUser("sa");
        spec.setDbPassword("");
        spec.getTables().add(new TableSpec("perf_user", 1));

        EngineResult r = ENGINE.execute(spec, noopListener());
        assertFalse(r.isSuccess());
        assertTrue(r.getErrorMsg().contains("不支持"), "未注册方言的 URL 应明确报错: " + r.getErrorMsg());
    }

    private static EngineListener noopListener() {
        return new EngineListener() {
            @Override
            public void onProgress(long total, long inserted, String table) {
            }

            @Override
            public void onHints(List<com.perftestor.datagen.model.MagicHint> m,
                                List<com.perftestor.datagen.model.RelationHint> r) {
            }
        };
    }
}
